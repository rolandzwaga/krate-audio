/// Strike-position amplitude for free-plate mode (m,n).
///
/// The circular-plate mode shape is  phi(r,theta) = R_{mn}(r) * cos(m*theta)
/// (Leissa; Rossing Ch.3). The strike weight is phi evaluated at the strike
/// point. The single user-facing Strike Position scalar is mapped to a 2-D point
/// that sweeps BOTH the radius and the azimuth, so every (m,n) mode -- including
/// the axisymmetric m=0 ring modes -- responds to the knob:
///   rho   = 0.40 + 0.50 * strikePos      -> [0.40, 0.90] radius fraction
///   theta = strikePos * (pi / 2)         -> azimuth sweep
/// Radial factor cos(n*pi*rho) gives n nodal circles with an antinode at the
/// FREE edge (rho = 1 -> |cos(n*pi)| = 1), unlike the old simply-supported model
/// that forced a node there. (This supersedes the rectangular SSSS diagonal-sweep
/// hack from correctness-audit Finding 8: the free-plate cos(m*theta) factor with
/// a non-trivial azimuth sweep excites every mode without the y0-node pathology.)
[[nodiscard]] inline float computePlateAmplitude(int modeIdx,
                                                 float strikePos) noexcept
{
    if (modeIdx < 0 || modeIdx >= kPlateMaxModeCount)
        return 0.0f;
    const PlateModeIndices idx = kPlateIndices[modeIdx];
    constexpr float kPi = std::numbers::pi_v<float>;
    const float rho   = 0.40f + 0.50f * strikePos;   // radius fraction
    const float theta = strikePos * (kPi * 0.5f);     // azimuth sweep
    const float fm = static_cast<float>(idx.m);
    const float fn = static_cast<float>(idx.n);
    return std::cos(fm * theta) * std::cos(fn * kPi * rho);
}

