// ==============================================================================
// Plate Mode Constants -- Free-plate Chladni (m + 2n) modal ratios
// ==============================================================================
// Sources:
//   - Chladni, E.F.F. (1802): "Die Akustik" -- the (m + 2n) nodal-figure law.
//   - Rossing, T.D. & Peterson, R.W. (1982/1986): cymbal/gong modal analysis,
//     JASA; Rossing, "Science of Percussion Instruments" Ch.3 (plates/cymbals).
//   - Fletcher, N.H. (1999): "The nonlinear physics of musical instruments".
//   - Leissa, A.W. (1969): "Vibration of Plates" (free circular plate).
//   - Spec 135 "Plate" body reference.
//
// PHYSICS CHANGE (signal-path audit §3-B, "Plate uses SSSS (m^2+n^2)/2 ratios"):
// the previous table used the SIMPLY-SUPPORTED (hinged) square-plate eigenvalues
//   f_{m,n} / f_{1,1} = (m^2 + n^2) / 2
// which describe a plate pinned at all four edges. A struck cymbal/gong has FREE
// edges, so its partials follow Chladni's power law in (m + 2n):
//   f_{m,n} = C * (m + 2n)^P
// where m = nodal DIAMETERS, n = nodal CIRCLES. The SSSS ladder was quasi-regular
// with exact degenerate repeats (12.5 and 25.0 each appeared twice) -- MORE
// ordered than a real inharmonic plate -- so Size/Material/Stretch/Scatter only
// scaled the same skeleton and metallic presets converged on one spectrum.
//
// Implementation notes (honest about what is/ isn't measured):
//   - P = 1.7 is the measured-cymbal Chladni exponent reported by Rossing &
//     Peterson (the classical Kirchhoff exponent is 2; real cymbals sit lower,
//     which also packs the upper partials denser -> shimmer).
//   - Pure (m + 2n)^P leaves exact degeneracies (e.g. (2,0) and (0,1) both have
//     m+2n = 2). A real free plate splits these -- circular-node families are
//     stiffer and sit sharp of the pure power law. We model that with a small
//     per-circular-family term (1 + kappa*n), kappa = 0.11. This is a perceptual
//     fit (like the Stretch B_max range), NOT an exact Leissa eigenvalue table.
//   - Rigid-body modes (0,0) translation and (1,0) tilt are excluded; the
//     fundamental is the (2,0) "two-diameter" mode.
//
// The (m,n) grid and the ratio table are generated together (tools-side
// gen_plate_chladni.js, P=1.7 kappa=0.11) and MUST stay in lock-step: the
// resonator-bank consumers read frequency from kPlateRatios[k] and strike
// amplitude from kPlateIndices[k] (plate_mapper.h / noise_body_mapper.h).
//
// Phase 8B keeps the 48-entry table (6 clean AVX2 kernel iters); Noise Body
// reuses the same arrays (FR-025 / FR-062).
// ==============================================================================

