enum class MonoOp : uint8_t {
    Prepare,             // a = sample rate
    NoteOn,              // a = note, b = velocity
    NoteOff,             // a = note
    SetMode,             // a = MonoMode value
    SetLegato,           // a != 0 -> enabled
    SetPortamentoTime,   // a = IEEE-754 bit pattern of the float ms (may be NaN / Inf / out of range)
    SetPortamentoMode,   // a = PortaMode value
    Reset,
    Process              // samples = number of processPortamento() calls
};

struct MonoStep {
    MonoOp op;
    double a;
    double b;
    int samples;
};

const char* opName(MonoOp op) {
    switch (op) {
        case MonoOp::Prepare: return "prepare";
        case MonoOp::NoteOn: return "noteOn";
        case MonoOp::NoteOff: return "noteOff";
        case MonoOp::SetMode: return "setMode";
        case MonoOp::SetLegato: return "setLegato";
        case MonoOp::SetPortamentoTime: return "setPortamentoTime";
        case MonoOp::SetPortamentoMode: return "setPortamentoMode";
        case MonoOp::Reset: return "reset";
        case MonoOp::Process: return "process";
    }
    return "?";
}

/// Builder so the transcriptions below read like the original call sequences.
struct Script {
    std::string name;
    std::vector<MonoStep> steps;

    explicit Script(std::string n) : name(std::move(n)) {}

    Script& prepare(double sr) { steps.push_back({MonoOp::Prepare, sr, 0.0, 0}); return *this; }
    Script& on(int note, int vel = 100) {
        steps.push_back({MonoOp::NoteOn, static_cast<double>(note), static_cast<double>(vel), 0});
        return *this;
    }
    Script& off(int note) { steps.push_back({MonoOp::NoteOff, static_cast<double>(note), 0.0, 0}); return *this; }
    Script& mode(int m) { steps.push_back({MonoOp::SetMode, static_cast<double>(m), 0.0, 0}); return *this; }
    Script& legato(bool on) { steps.push_back({MonoOp::SetLegato, on ? 1.0 : 0.0, 0.0, 0}); return *this; }
    Script& porta(double ms) { return portaBits(std::bit_cast<uint32_t>(static_cast<float>(ms))); }
    Script& portaBits(uint32_t pattern) {
        steps.push_back({MonoOp::SetPortamentoTime, static_cast<double>(pattern), 0.0, 0});
        return *this;
    }
    Script& portaMode(int m) { steps.push_back({MonoOp::SetPortamentoMode, static_cast<double>(m), 0.0, 0}); return *this; }
    Script& reset() { steps.push_back({MonoOp::Reset, 0.0, 0.0, 0}); return *this; }
    Script& process(int n) { steps.push_back({MonoOp::Process, 0.0, 0.0, n}); return *this; }
};

struct ReplayStats {
    std::size_t steps = 0;
    std::size_t comparisons = 0;
    std::size_t mismatches = 0;
    std::string firstMismatch;
};

uint32_t bits(float x) noexcept { return std::bit_cast<uint32_t>(x); }

/// Float from its bit pattern through a volatile sink, so a non-finite value
/// exists at runtime under -ffast-math too (no constant folding, no FP
/// conversion of a NaN/Inf literal).
float floatFromBits(uint32_t pattern) noexcept {
    volatile uint32_t sink = pattern;
    const uint32_t read = sink;
    return std::bit_cast<float>(read);
}

constexpr uint32_t kNaNBits = 0x7FC00000U;
constexpr uint32_t kPosInfBits = 0x7F800000U;

struct Comparator {
    ReplayStats* stats;
    std::size_t stepIndex = 0;
    MonoOp op = MonoOp::Reset;

    void fail(const char* what, uint64_t liveV, uint64_t refV, int sample) const {
        ++stats->mismatches;
        if (stats->firstMismatch.empty()) {
            std::ostringstream os;
            os << "step " << stepIndex << " (" << opName(op) << ")";
            if (sample >= 0) os << " sample " << sample;
            os << ": " << what << " live=0x" << std::hex << liveV << " ref=0x" << refV;
            stats->firstMismatch = os.str();
        }
    }
    void eqFloat(const char* what, float live, float ref, int sample = -1) const {
        ++stats->comparisons;
        if (bits(live) != bits(ref)) fail(what, bits(live), bits(ref), sample);
    }
    void eqU(const char* what, uint64_t live, uint64_t ref, int sample = -1) const {
        ++stats->comparisons;
        if (live != ref) fail(what, live, ref, sample);
    }
    void eqEvent(const Live::MonoNoteEvent& l, const Ref::MonoNoteEvent& r) const {
        eqFloat("event.frequency", l.frequency, r.frequency);
        eqU("event.velocity", l.velocity, r.velocity);
        eqU("event.retrigger", l.retrigger ? 1U : 0U, r.retrigger ? 1U : 0U);
        eqU("event.isNoteOn", l.isNoteOn ? 1U : 0U, r.isNoteOn ? 1U : 0U);
    }
};

/// Apply each step to the live handler and to the frozen reference; compare
/// bitwise. When `sameModeSetEvery100` is true, setGlideMode(ConstantTime) is
/// called on the live handler before every 100th step (a same-mode set must be
/// a no-op).
ReplayStats monoReplay(Live::MonoHandler& live, Ref::MonoHandler& ref,
                       const std::vector<MonoStep>& script, bool sameModeSetEvery100 = true) {
    ReplayStats stats;
    Comparator cmp{&stats};
    for (std::size_t i = 0; i < script.size(); ++i) {
        const MonoStep& s = script[i];
        cmp.stepIndex = i;
        cmp.op = s.op;
        if (sameModeSetEvery100 && (i % 100) == 0) {
            live.setGlideMode(Live::GlideMode::ConstantTime);
        }
        switch (s.op) {
            case MonoOp::Prepare:
                live.prepare(s.a);
                ref.prepare(s.a);
                break;
            case MonoOp::NoteOn: {
                const auto l = live.noteOn(static_cast<int>(s.a), static_cast<int>(s.b));
                const auto r = ref.noteOn(static_cast<int>(s.a), static_cast<int>(s.b));
                cmp.eqEvent(l, r);
                break;
            }
            case MonoOp::NoteOff: {
                const auto l = live.noteOff(static_cast<int>(s.a));
                const auto r = ref.noteOff(static_cast<int>(s.a));
                cmp.eqEvent(l, r);
                break;
            }
            case MonoOp::SetMode:
                live.setMode(static_cast<Live::MonoMode>(static_cast<uint8_t>(s.a)));
                ref.setMode(static_cast<Ref::MonoMode>(static_cast<uint8_t>(s.a)));
                break;
            case MonoOp::SetLegato:
                live.setLegato(s.a != 0.0);
                ref.setLegato(s.a != 0.0);
                break;
            case MonoOp::SetPortamentoTime: {
                const auto pattern = static_cast<uint32_t>(s.a);
                live.setPortamentoTime(floatFromBits(pattern));
                ref.setPortamentoTime(floatFromBits(pattern));
                break;
            }
            case MonoOp::SetPortamentoMode:
                live.setPortamentoMode(static_cast<Live::PortaMode>(static_cast<uint8_t>(s.a)));
                ref.setPortamentoMode(static_cast<Ref::PortaMode>(static_cast<uint8_t>(s.a)));
                break;
            case MonoOp::Reset:
                live.reset();
                ref.reset();
                break;
            case MonoOp::Process:
                for (int n = 0; n < s.samples; ++n) {
                    const float l = live.processPortamento();
                    const float r = ref.processPortamento();
                    cmp.eqFloat("processPortamento()", l, r, n);
                    cmp.eqFloat("getCurrentFrequency()", live.getCurrentFrequency(),
                                ref.getCurrentFrequency(), n);
                }
                break;
        }
        cmp.eqFloat("getCurrentFrequency()", live.getCurrentFrequency(), ref.getCurrentFrequency());
        cmp.eqU("hasActiveNote()", live.hasActiveNote() ? 1U : 0U, ref.hasActiveNote() ? 1U : 0U);
        cmp.eqU("glideMode()", static_cast<uint64_t>(live.glideMode()),
                static_cast<uint64_t>(Live::GlideMode::ConstantTime));
        ++stats.steps;
    }
    return stats;
}

