// T008: SC-007 ConstantRate law (FR-022, FR-026, D-13)
// =============================================================================
// T is the ONE portamento knob (setPortamentoTime), read as ms per octave in
// ConstantRate (FR-026). Sample 1 is the first processPortamento() after the
// noteOn. 2026-10-12 O-1 ruling: no upward-rate floor, so the duration law is
// T*|delta|/12 in both directions at every rate.

namespace {

constexpr int kRateStartNote = 60;

/// Pitch in semitones of a frequency (double, from the float output).
double pitchOf(float hz) {
    return 69.0 + 12.0 * std::log2(static_cast<double>(hz) / 440.0);
}

/// The settled frequency of `note`: a second handler snapped to it with T = 0.
float settledFrequency(double sampleRate, int note) {
    Live::MonoHandler snap;
    snap.prepare(sampleRate);
    (void)snap.noteOn(note, 100);  // first note ever, T = 0: snaps
    return snap.processPortamento();
}

/// Snap to the start note (first noteOn), release it, then a staccato noteOn
/// (PortaMode::Always, the default) to start + delta, which glides.
void startConstantRateGlide(Live::MonoHandler& m, double sampleRate, float timeMs, int delta) {
    m.prepare(sampleRate);
    m.setGlideMode(Live::GlideMode::ConstantRate);
    m.setPortamentoTime(timeMs);
    (void)m.noteOn(kRateStartNote, 100);
    (void)m.noteOff(kRateStartNote);
    (void)m.noteOn(kRateStartNote + delta, 100);
}

/// 1-based index of the first sample whose output equals `target` bitwise, 0 if none.
std::size_t firstSettledSample(const std::vector<float>& out, float target) {
    for (std::size_t i = 0; i < out.size(); ++i) {
        if (bits(out[i]) == bits(target)) return i + 1;
    }
    return 0;
}

/// True if every sample from 1-based `from` on equals `target` bitwise.
bool staysSettled(const std::vector<float>& out, std::size_t from, float target) {
    for (std::size_t i = from - 1; i < out.size(); ++i) {
        if (bits(out[i]) != bits(target)) return false;
    }
    return true;
}

/// Least-squares slope (semitones per sample) of pitchOf(out[n-1]) against n
/// over the 1-based inclusive range [first, last].
double pitchSlope(const std::vector<float>& out, std::size_t first, std::size_t last) {
    const auto count = static_cast<double>(last - first + 1);
    double meanX = 0.0;
    double meanY = 0.0;
    for (std::size_t n = first; n <= last; ++n) {
        meanX += static_cast<double>(n);
        meanY += pitchOf(out[n - 1]);
    }
    meanX /= count;
    meanY /= count;
    double sxy = 0.0;
    double sxx = 0.0;
    for (std::size_t n = first; n <= last; ++n) {
        const double dx = static_cast<double>(n) - meanX;
        sxy += dx * (pitchOf(out[n - 1]) - meanY);
        sxx += dx * dx;
    }
    return sxy / sxx;
}

/// Interior [0.05 n_end, 0.95 n_end] of a glide that settles at n_end.
std::pair<std::size_t, std::size_t> interiorOf(std::size_t nEnd) {
    const auto end = static_cast<double>(nEnd);
    return {static_cast<std::size_t>(std::ceil(0.05 * end)),
            static_cast<std::size_t>(std::floor(0.95 * end))};
}

std::vector<float> renderGlide(Live::MonoHandler& m, std::size_t samples) {
    std::vector<float> out(samples);
    for (auto& v : out) v = m.processPortamento();
    return out;
}

}  // namespace

