#!/usr/bin/env node
//
// lint-site-seo.js
// =============================================================================
// Checks the krateaudio.com pages for the search-engine basics: every page has one title (at most 60 characters), one
// meta description (50-160), a canonical URL that is the page's own address, Open Graph tags with an image that
// exists, one <h1>, images with alt text and dimensions, parseable structured data, no unreplaced template
// placeholder, and a sitemap that lists exactly the indexable pages.
//
// WHY. krateaudio.com served four plugin pages with the literal canonical "{{URL}}" and a sitemap missing a plugin for
// weeks, and nothing noticed: the pages were generated by two workflows and never read back. tools/gen-site.js runs
// checkSite() over everything it writes before a deploy; this CLI builds the site from the working tree into a
// temporary directory (every plugin with a landing page counts as released at its version.json version, manuals
// rendered by a pandoc stand-in, no git history needed) and checks that, so a template edit is caught at commit time.
//
// Usage: node tools/lint-site-seo.js [--self-test]
// Exit codes: 0 = clean, 1 = findings (one stderr line each), 2 = internal error.
// =============================================================================
'use strict';

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const { SITE_ORIGIN } = require('./site/common.js');

const NAME = 'lint-site-seo';
const TITLE_MAX = 60;
const TITLE_MIN = 15;
const DESC_MIN = 50;
const DESC_MAX = 160;

function listFiles(dir, base = dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(full, base));
    else out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out.sort();
}

/** The address a file is served at: "iterum/index.html" -> https://krateaudio.com/iterum/. */
function urlOf(relPath) {
  return `${SITE_ORIGIN}/${relPath.replace(/(^|\/)index\.html$/, '$1')}`;
}

/** The site file an absolute or page-relative link points at, or null when it leaves the site. */
function targetOf(href, pageRel) {
  let p = href.split('#')[0].split('?')[0];
  if (p === '') return null;
  if (p.startsWith(SITE_ORIGIN)) p = p.slice(SITE_ORIGIN.length) || '/';
  else if (/^[a-z][a-z0-9+.-]*:/i.test(p) || p.startsWith('//')) return null;
  const resolved = p.startsWith('/') ? p.slice(1) : path.posix.join(path.posix.dirname(pageRel), p);
  const norm = path.posix.normalize(resolved === '' ? '.' : resolved).replace(/^\.(?:\/|$)/, '');
  if (norm === '') return 'index.html';
  return norm.endsWith('/') ? `${norm}index.html` : norm;
}

function all(re, text) {
  return [...text.matchAll(re)].map((m) => m[1]);
}

function attr(tag, name) {
  const m = new RegExp(`\\b${name}="([^"]*)"`, 'i').exec(tag);
  return m ? m[1] : null;
}

function decode(text) {
  return text.replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
}

function meta(html, key, value) {
  return [...html.matchAll(/<meta\b[^>]*>/gi)]
    .map((m) => m[0])
    .filter((tag) => attr(tag, key) === value)
    .map((tag) => decode(attr(tag, 'content') ?? ''));
}

/** Findings for one page; @p exists(rel) answers whether a site file exists (or is outside a partial build). */
function checkPage(rel, html, exists) {
  const f = [];
  const add = (msg) => f.push(`${rel}: ${msg}`);
  const is404 = rel === '404.html';

  if (!/<html\b[^>]*\blang="[a-z-]+"/i.test(html)) add('<html> has no lang attribute');
  const left = [...new Set(html.match(/\{\{[A-Z_]+\}\}|\$(?:body|toc|title)\$/g) ?? [])];
  if (left.length > 0) add(`unreplaced placeholder ${left.join(' ')}`);

  // Only the document head: an inline SVG (the pre-rendered signal-flow diagrams) carries a <title> per node.
  const head = /<head>([\s\S]*?)<\/head>/i.exec(html)?.[1] ?? '';
  const titles = all(/<title>([^<]*)<\/title>/gi, head).map((t) => decode(t).trim());
  if (titles.length !== 1) add(`${titles.length} <title> elements, want 1`);
  else if (titles[0].length > TITLE_MAX || titles[0].length < TITLE_MIN) {
    add(`title is ${titles[0].length} characters, want ${TITLE_MIN}-${TITLE_MAX}: "${titles[0]}"`);
  }

  const descs = meta(html, 'name', 'description');
  if (descs.length !== 1) add(`${descs.length} meta descriptions, want 1`);
  else if (descs[0].length > DESC_MAX || descs[0].length < DESC_MIN) {
    add(`meta description is ${descs[0].length} characters, want ${DESC_MIN}-${DESC_MAX}`);
  }

  const robots = meta(html, 'name', 'robots');
  if (is404 !== robots.some((r) => /noindex/.test(r))) add(is404 ? '404 page is not noindex' : 'page is noindex');

  const canon = [...html.matchAll(/<link\b[^>]*\brel="canonical"[^>]*>/gi)].map((m) => attr(m[0], 'href'));
  if (!is404) {
    if (canon.length !== 1) add(`${canon.length} canonical links, want 1`);
    else if (canon[0] !== urlOf(rel)) add(`canonical ${canon[0]} is not ${urlOf(rel)}`);
    const ogUrl = meta(html, 'property', 'og:url');
    if (ogUrl.length !== 1 || ogUrl[0] !== urlOf(rel)) add(`og:url ${JSON.stringify(ogUrl)} is not ${urlOf(rel)}`);
    for (const p of ['og:title', 'og:description', 'og:type']) {
      if (meta(html, 'property', p).length !== 1) add(`no single ${p}`);
    }
  }
  const ogImage = meta(html, 'property', 'og:image');
  if (ogImage.length !== 1) add(`${ogImage.length} og:image tags, want 1`);
  else if (!ogImage[0].startsWith(`${SITE_ORIGIN}/`)) add(`og:image ${ogImage[0]} is not on ${SITE_ORIGIN}`);
  else if (!exists(targetOf(ogImage[0], rel))) add(`og:image ${ogImage[0]} does not exist`);
  if (meta(html, 'name', 'twitter:card').length !== 1) add('no single twitter:card');

  const h1 = html.match(/<h1\b/gi) ?? [];
  if (h1.length !== 1) add(`${h1.length} <h1> elements, want 1`);

  for (const m of html.matchAll(/<img\b[^>]*>/gi)) {
    const tag = m[0];
    const src = attr(tag, 'src') ?? '';
    if (!(attr(tag, 'alt') ?? '').trim()) add(`<img src="${src}"> has no alt text`);
    if (attr(tag, 'width') === null || attr(tag, 'height') === null) add(`<img src="${src}"> has no width/height`);
    const target = targetOf(src, rel);
    if (target !== null && !exists(target)) add(`<img src="${src}"> does not exist`);
  }

  for (const m of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/gi)) {
    try {
      JSON.parse(m[1]);
    } catch (err) {
      add(`structured data does not parse: ${err.message}`);
    }
  }

  for (const href of all(/<a\b[^>]*\bhref="([^"]*)"/gi, html)) {
    const target = targetOf(decode(href), rel);
    if (target !== null && !exists(target)) add(`link ${href} does not resolve to a page`);
  }
  return { findings: f, title: titles[0], description: descs[0], noindex: is404 };
}

/**
 * Findings for a built site directory. @p partial: the directory holds only some pages (release.yml's single-plugin
 * build, or a build without manuals), so a link or sitemap entry may point at a page that is not in it.
 */
function checkSite(dir, { partial = false } = {}) {
  const files = listFiles(dir);
  const fileSet = new Set(files);
  const exists = (rel) => fileSet.has(rel) || partial;
  const findings = [];
  const seenTitle = new Map();
  const seenDesc = new Map();
  const indexable = [];

  for (const rel of files.filter((r) => r.endsWith('.html') && !/^google[0-9a-f]+\.html$/.test(r))) {
    const page = checkPage(rel, fs.readFileSync(path.join(dir, rel), 'utf8'), exists);
    findings.push(...page.findings);
    if (page.noindex) continue;
    indexable.push(urlOf(rel));
    for (const [map, value, what] of [[seenTitle, page.title, 'title'], [seenDesc, page.description, 'meta description']]) {
      if (value === undefined) continue;
      if (map.has(value)) findings.push(`${rel}: same ${what} as ${map.get(value)}`);
      else map.set(value, rel);
    }
  }

  if (!fileSet.has('sitemap.xml')) findings.push('sitemap.xml: missing');
  else {
    const xml = fs.readFileSync(path.join(dir, 'sitemap.xml'), 'utf8');
    const locs = all(/<loc>([^<]*)<\/loc>/g, xml).map(decode);
    const seen = new Set();
    for (const loc of locs) {
      if (seen.has(loc)) findings.push(`sitemap.xml: ${loc} listed twice`);
      seen.add(loc);
      if (!loc.startsWith(`${SITE_ORIGIN}/`)) findings.push(`sitemap.xml: ${loc} is not on ${SITE_ORIGIN}`);
      else if (!partial && !fileSet.has(targetOf(loc, ''))) findings.push(`sitemap.xml: ${loc} has no page`);
    }
    for (const lastmod of all(/<lastmod>([^<]*)<\/lastmod>/g, xml)) {
      if (Number.isNaN(Date.parse(lastmod))) findings.push(`sitemap.xml: lastmod ${lastmod} is not a date`);
    }
    for (const url of indexable) if (!seen.has(url)) findings.push(`sitemap.xml: indexable page ${url} is not listed`);
  }
  if (!fileSet.has('robots.txt')) findings.push('robots.txt: missing');
  else if (!fs.readFileSync(path.join(dir, 'robots.txt'), 'utf8').includes(`Sitemap: ${SITE_ORIGIN}/sitemap.xml`)) {
    findings.push('robots.txt: does not name the sitemap');
  }
  return findings;
}

/** Builds the site from the working tree into a temporary directory and checks it (see the header). */
async function lintWorkingTree(root) {
  const gen = require('./gen-site.js');
  const prod = gen.productionDeps(root);
  const versionOf = (dir) => JSON.parse(prod.readFile(path.join(root, 'plugins', dir, 'version.json'))).version;
  const deps = {
    ...prod,
    repo: () => process.env.REPO || 'rolandzwaga/krate-audio',
    gitTags: (pattern) => {
      const m = /^([^/]+)\/v\*$/.exec(pattern);
      if (!m || m[1] === 'manager' || !prod.isFile(path.join(root, 'plugins', m[1], 'version.json'))) return [];
      return [`${m[1]}/v${versionOf(m[1])}`];
    },
    commitDate: () => '',
    pandoc: gen.stubPandoc(prod.readFile),
    renderDot: async () => null,
  };
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'krate-site-'));
  try {
    let err = '';
    const io = { stdout: { write: () => true }, stderr: { write: (s) => ((err += s), true) } };
    const code = await gen.main(['--out', out], io, deps);
    return code === 0 ? [] : err.trim().split('\n').map((l) => l.replace(/^gen-site: (E_SITE_LINT: )?/, ''));
  } finally {
    fs.rmSync(out, { recursive: true, force: true });
  }
}

// --- self-test -----------------------------------------------------------------------------------------------------

function page({ p = '/x/', title = 'A page title of fine length', desc, h1 = 1, extra = '', robots = 'index, follow' }) {
  const d = desc ?? 'A meta description that is long enough to pass the lower bound of fifty characters.';
  return [
    '<!DOCTYPE html><html lang="en"><head>',
    `<title>${title}</title>`,
    `<meta name="description" content="${d}">`,
    `<meta name="robots" content="${robots}">`,
    `<link rel="canonical" href="${SITE_ORIGIN}${p}">`,
    `<meta property="og:url" content="${SITE_ORIGIN}${p}">`,
    '<meta property="og:title" content="t"><meta property="og:description" content="d"><meta property="og:type" content="website">',
    `<meta property="og:image" content="${SITE_ORIGIN}/og.png">`,
    '<meta name="twitter:card" content="summary_large_image">',
    '</head><body>',
    '<h1>H</h1>'.repeat(h1),
    extra,
    '</body></html>',
  ].join('\n');
}

function selfTest() {
  const cases = [];
  const site = (files, expect, opts) => cases.push({ files, expect, opts });
  const base = (pages) => ({
    'og.png': '',
    'robots.txt': `Sitemap: ${SITE_ORIGIN}/sitemap.xml\n`,
    'sitemap.xml': `<urlset>${Object.keys(pages)
      .filter((p) => p !== '404.html')
      .map((p) => `<url><loc>${urlOf(p)}</loc><lastmod>2026-11-20</lastmod></url>`)
      .join('')}</urlset>`,
    ...pages,
  });
  site(base({ 'x/index.html': page({}) }), []);
  site(base({ 'x/index.html': page({ title: 'Iterum - Multi-Mode Delay {{URL}} | Krate Audio' }) }), ['unreplaced placeholder {{URL}}']);
  site(base({ 'x/index.html': page({ title: 'x'.repeat(61) }) }), ['title is 61 characters']);
  site(base({ 'x/index.html': page({ extra: '<svg><g><title>node</title></g></svg>' }) }), []);
  site(base({ 'x/index.html': page({ desc: 'too short' }) }), ['meta description is 9 characters']);
  site(base({ 'x/index.html': page({ p: '/y/' }) }), ['canonical https://krateaudio.com/y/ is not', 'og:url']);
  site(base({ 'x/index.html': page({ h1: 2 }) }), ['2 <h1> elements']);
  site(base({ 'x/index.html': page({ extra: '<img src="a.png">' }) }), ['has no alt text', 'has no width/height', 'does not exist']);
  site(base({ 'x/index.html': page({ extra: '<script type="application/ld+json">{nope</script>' }) }), ['structured data does not parse']);
  site(base({ 'x/index.html': page({ extra: '<a href="/missing/">m</a>' }) }), ['link /missing/ does not resolve']);
  site(base({ 'x/index.html': page({ extra: '<a href="/missing/">m</a>' }) }), [], { partial: true });
  site(base({ 'x/index.html': page({}), 'y/index.html': page({ p: '/y/' }) }), ['same title as x/index.html', 'same meta description']);
  site({ ...base({ 'x/index.html': page({}) }), 'sitemap.xml': '<urlset></urlset>' }, ['indexable page https://krateaudio.com/x/ is not listed']);
  site({ ...base({ 'x/index.html': page({}) }), 'robots.txt': 'User-agent: *' }, ['robots.txt: does not name the sitemap']);
  site(base({ 'x/index.html': page({}), '404.html': page({ p: '/404.html', title: 'Page not found | Krate Audio' }) }), [
    '404 page is not noindex',
  ]);

  let failed = 0;
  for (const [i, c] of cases.entries()) {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lint-site-seo-'));
    try {
      for (const [rel, text] of Object.entries(c.files)) {
        fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true });
        fs.writeFileSync(path.join(dir, rel), text);
      }
      const got = checkSite(dir, c.opts);
      const ok =
        c.expect.length === 0 ? got.length === 0 : c.expect.every((e) => got.some((g) => g.includes(e)));
      if (!ok) {
        failed += 1;
        process.stderr.write(`${NAME} self-test case ${i}: want ${JSON.stringify(c.expect)}, got ${JSON.stringify(got)}\n`);
      }
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  }
  process.stdout.write(`${NAME} self-test: ${cases.length - failed}/${cases.length} cases pass\n`);
  return failed === 0 ? 0 : 1;
}

async function cli(argv) {
  if (argv.length === 1 && argv[0] === '--self-test') return selfTest();
  if (argv.length !== 0) {
    process.stderr.write(`usage: node tools/${NAME}.js [--self-test]\n`);
    return 2;
  }
  const findings = await lintWorkingTree(path.resolve(__dirname, '..'));
  for (const f of findings) process.stderr.write(`${NAME}: ${f}\n`);
  if (findings.length === 0) process.stdout.write(`${NAME}: clean\n`);
  return findings.length === 0 ? 0 : 1;
}

module.exports = { checkSite, checkPage, urlOf, targetOf, lintWorkingTree };

if (require.main === module) {
  cli(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (err) => {
      process.stderr.write(`${NAME}: internal error: ${err.stack}\n`);
      process.exitCode = 2;
    },
  );
}
