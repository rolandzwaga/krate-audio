#!/usr/bin/env node
// Generates the coefficient table of dsp/include/krate/dsp/core/log_cosh_table.h: g(a) = ln(1 + exp(-2a)) on
// [0, 20) as 80 degree-5 polynomials in u = a - 0.25 * seg (seg = floor(4a)), each the interpolant at the six
// Chebyshev nodes of its segment. Usage: node tools/gen-log-cosh-table.js > dsp/include/krate/dsp/core/log_cosh_table.h
'use strict';

const kSegments = 80;
const kWidth = 0.25;
const kDegree = 5;

const g = (a) => Math.log1p(Math.exp(-2 * a));

// Monomial coefficients (in u, ascending) of the interpolant through (u_k, y_k), by Gauss-Jordan elimination with
// partial pivoting on the Vandermonde system.
function solveVandermonde(us, ys) {
  const n = us.length;
  const m = us.map((u, r) => {
    const row = [];
    let p = 1;
    for (let c = 0; c < n; ++c) {
      row.push(p);
      p *= u;
    }
    row.push(ys[r]);
    return row;
  });
  for (let c = 0; c < n; ++c) {
    let piv = c;
    for (let r = c + 1; r < n; ++r) if (Math.abs(m[r][c]) > Math.abs(m[piv][c])) piv = r;
    [m[c], m[piv]] = [m[piv], m[c]];
    for (let r = 0; r < n; ++r) {
      if (r === c) continue;
      const f = m[r][c] / m[c][c];
      for (let k = c; k <= n; ++k) m[r][k] -= f * m[c][k];
    }
  }
  return m.map((row, c) => row[n] / row[c]);
}

const rows = [];
let worst = 0;
for (let seg = 0; seg < kSegments; ++seg) {
  const lo = kWidth * seg;
  const us = [];
  const ys = [];
  for (let k = 0; k <= kDegree; ++k) {
    const x = Math.cos((Math.PI * (k + 0.5)) / (kDegree + 1));
    const u = 0.5 * kWidth * (x + 1);
    us.push(u);
    ys.push(g(lo + u));
  }
  const c = solveVandermonde(us, ys);
  for (let i = 0; i <= 1000; ++i) {
    const u = (kWidth * i) / 1000;
    let p = 0;
    for (let k = kDegree; k >= 0; --k) p = p * u + c[k];
    worst = Math.max(worst, Math.abs(p - g(lo + u)));
  }
  rows.push(`    {${c.map((v) => v.toPrecision(17)).join(', ')}},`);
}

process.stdout.write(`// ==============================================================================
// Layer 0: Core Utilities - ln(1 + exp(-2a)) coefficient table
// ==============================================================================
// GENERATED by tools/gen-log-cosh-table.js - do not edit by hand.
//
// g(a) = ln(1 + exp(-2a)) on [0, 20) as ${kSegments} polynomials of degree ${kDegree} in u = a - ${kWidth} * seg,
// seg = floor(4a), each the interpolant at its segment's six Chebyshev nodes. Worst |error| of the double
// coefficients against the double g over 1001 points per segment: ${worst.toExponential(3)}.
// Consumer: TanhADAA::F1Fast (primitives/tanh_adaa.h), ln(cosh x) = |x| - ln 2 + g(|x|).
// ==============================================================================

#pragma once

#include <array>

namespace Krate::DSP::detail {

inline constexpr int kLogCoshSegments = ${kSegments};
inline constexpr float kLogCoshSegmentsPerUnit = ${1 / kWidth}.0f;
inline constexpr float kLogCoshSegmentWidth = ${kWidth}f;

inline constexpr std::array<std::array<double, ${kDegree + 1}>, kLogCoshSegments> kLogCoshTable{{
${rows.join('\n')}
}};

}  // namespace Krate::DSP::detail
`);
