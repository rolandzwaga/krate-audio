#!/usr/bin/env bash
# Profundum Phase 8, task T018 close lane: change-set scope check, per-push lane and the phase's own [long] lane
# (FR-088, FR-089). Structure copied from specs/profundum-phase7-stereo-field/evidence/close/suites.sh, with the
# scope rule of 2026-10-18 (Phase 6 ruling G9-4, root CLAUDE.md "Run only the tests the change set can reach").
#
# Run from the main loop AFTER T015, DETACHED, so it survives the 2 h background-task ceiling (Git Bash, from the
# Bash tool):
#   nohup bash specs/profundum-phase8-bass-morph/evidence/close/suites.sh \
#       > specs/profundum-phase8-bass-morph/evidence/run-log/close/suites.out 2>&1 & disown
# and run tidy.sh concurrently. Watch evidence/run-log/close/status.txt; its last line is "DONE ...".
#
# Steps:
#   1. One rebuild of dsp_systems_tests (wall clock recorded; the count of "warning C|warning:" lines in the build
#      log must be 0).
#   2. Change-set scope (BASE_COMMIT 964045a4): git diff --name-only over dsp/include dsp/src plugins/shared
#      tests/test_helpers must be EMPTY, and the untracked files under dsp/include must be exactly
#      dsp/include/krate/dsp/systems/morph_state.h and dsp/include/krate/dsp/systems/bass_morph_engine.h (FR-088).
#      Any other path is RED and is written to the status file with the consumer executables whose full suites it
#      requires; those consumers are then rebuilt (one build call) and their full per-push suites run in step 3
#      (the full suites of every consumer of a shared header the phase modified). With the expected diff no
#      consumer suite (Ruinae, Seraphis, Vorago, Innexus, other dsp_*_tests) runs.
#   3. Concurrently:
#      (a) the per-push lane of the phase's executable:
#          dsp_systems_tests.exe "~[long]~[performance]~[perf]~[benchmark]~[!benchmark]" -D 15
#          to evidence/run-log/close/perpush-dsp_systems_tests.log (every case's duration printed, so an untagged
#          slow case shows up);
#      (b) the [long] lane of the PHASE'S OWN TUs ONLY: one shard per TEST_CASE in the list generated by
#          dsp_systems_tests.exe --list-tests "[bass-morph][long]~[performance]~[perf]~[benchmark]~[!benchmark]"
#          --verbosity quiet (never hand-kept; about 23 shards: 9 SC-004, 6 SC-008, 4 SC-016, 3 SC-017, 2 chain,
#          plus T015 re-tags), run through xargs -P min(shards, cores - 4), each shard to
#          evidence/run-log/close/long/<case>.log. Never every [long] case of the executable.
#      (c) only on a scope RED: each required consumer's full per-push suite, to
#          evidence/run-log/close/consumer-<exe>.log.
#   4. Summary block: per-shard verdict and wall clock (for the next run's sharding), the SC-004 worst ratio per
#      family, the SC-008 (c) / (d) minimum margins per shard, the SC-017 worst dBFS per fs.
# A timing-budget assertion of an untouched (non-Phase-8) case that fails under this concurrent lane is recorded as
# load, not re-run (root CLAUDE.md).
# Status file evidence/run-log/close/status.txt: one line per lane / shard: name, exit code, wall clock (s).
# Exit code: 0 only if every lane is green.
set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"
cd "$REPO" || exit 2

SPEC="specs/profundum-phase8-bass-morph"
CMAKE="/c/Program Files/CMake/bin/cmake.exe"
BUILD_DIR="build/windows-x64-release"
BIN="$BUILD_DIR/bin/Release"
EXE="dsp_systems_tests"
PERPUSH_FILTER="~[long]~[performance]~[perf]~[benchmark]~[!benchmark]"
LONG_FILTER="[bass-morph][long]~[performance]~[perf]~[benchmark]~[!benchmark]"
BASE_COMMIT="964045a4"
SCOPE_PATHS="dsp/include dsp/src plugins/shared tests/test_helpers"
LOGDIR="$SPEC/evidence/run-log/close"
LONGDIR="$LOGDIR/long"
STATUS="$LOGDIR/status.txt"
PERPUSH_LOG="$LOGDIR/perpush-$EXE.log"

# The two new Phase 8 headers (tasks.md "File map"; untracked); nothing tracked under the scope paths may differ
# from 964045a4.
ALLOWED="dsp/include/krate/dsp/systems/bass_morph_engine.h
dsp/include/krate/dsp/systems/morph_state.h"

CORES="$(nproc 2>/dev/null || echo 8)"

mkdir -p "$LOGDIR" "$LONGDIR"
rm -f "$LONGDIR"/*.log "$LONGDIR"/*.txt "$LOGDIR"/consumer-*.log

now() { date -u +%Y-%m-%dT%H:%M:%SZ; }
status_line() { echo "$*" >> "$STATUS"; }

suite_start="$(date +%s)"
echo "START $(now) commit $(git rev-parse --short HEAD 2>/dev/null || echo unknown) base $BASE_COMMIT cores $CORES" > "$STATUS"

# ---------------------------------------------------------------------------------------------------------------
# 1. One rebuild of dsp_systems_tests.
# ---------------------------------------------------------------------------------------------------------------
BUILD_LOG="$LOGDIR/build.log"
t0="$(date +%s)"
"$CMAKE" --build "$BUILD_DIR" --config Release --target "$EXE" > "$BUILD_LOG" 2>&1
build_status=$?
t1="$(date +%s)"
warnings="$(grep -ciE "warning C|warning:" "$BUILD_LOG" || true)"
status_line "build exit=$build_status wall=$((t1 - t0))s warnings=${warnings:-0} log=$BUILD_LOG"
if [ "$build_status" -ne 0 ]; then
    status_line "DONE $(now) RED: build failed; no test lane ran (see $BUILD_LOG)"
    tail -n 30 "$BUILD_LOG"
    exit 1
fi
if [ ! -f "$BIN/$EXE.exe" ]; then
    status_line "DONE $(now) RED: $BIN/$EXE.exe missing after the build"
    exit 1
fi

# ---------------------------------------------------------------------------------------------------------------
# 2. Change-set scope (FR-088). Recorded before the lanes so a RED is visible while they run.
# ---------------------------------------------------------------------------------------------------------------
# Consumer executables whose full suites a changed path requires.
consumers_for() {
    local p="$1" layers="" plugins="" inc out="" l pl
    case "$p" in
        dsp/include/krate/dsp/core/*)       layers="core primitives processors systems effects" ;;
        dsp/include/krate/dsp/primitives/*) layers="primitives processors systems effects" ;;
        dsp/include/krate/dsp/processors/*) layers="processors systems effects" ;;
        dsp/include/krate/dsp/systems/*)    layers="systems effects" ;;
        dsp/include/krate/dsp/effects/*)    layers="effects" ;;
        dsp/src/*|dsp/include/*|tests/test_helpers/*) layers="core primitives processors systems effects" ;;
    esac
    case "$p" in
        dsp/include/krate/dsp/*)
            inc="krate/dsp/${p#dsp/include/krate/dsp/}"
            # Direct includers only; a transitive consumer still needs a check by hand.
            plugins="$(grep -rlF "$inc" plugins 2>/dev/null | cut -d/ -f2 | sort -u | tr '\n' ' ')" ;;
        dsp/src/*|plugins/shared/*|tests/test_helpers/*)
            plugins="disrumpo gradus innexus iterum membrum ruinae seraphis shared vorago" ;;
    esac
    for l in $layers; do out="$out dsp_${l}_tests"; done
    for pl in $plugins; do
        case "$pl" in
            iterum) out="$out plugin_tests approval_tests" ;;
            *)      out="$out ${pl}_tests" ;;
        esac
    done
    echo "${out# }"
}

SCOPE_LOG="$LOGDIR/scope-diff.log"
# shellcheck disable=SC2086
{
    echo "=== git diff --name-only $BASE_COMMIT -- $SCOPE_PATHS (must be empty)"
    git diff --name-only "$BASE_COMMIT" -- $SCOPE_PATHS
    echo "=== untracked under dsp/include (must be exactly the two Phase 8 headers)"
    git ls-files --others --exclude-standard -- dsp/include
} > "$SCOPE_LOG" 2>&1
# shellcheck disable=SC2086
tracked_changed="$(git diff --name-only "$BASE_COMMIT" -- $SCOPE_PATHS | tr -d '\r' | grep -v '^$' | sort -u)"
untracked="$(git ls-files --others --exclude-standard -- dsp/include | tr -d '\r' | grep -v '^$' | sort -u)"
allowed_sorted="$(printf '%s\n' "$ALLOWED" | sort -u)"
unexpected_untracked="$(comm -23 <(printf '%s\n' "$untracked" | grep -v '^$') <(printf '%s\n' "$allowed_sorted"))"
missing="$(comm -13 <(printf '%s\n' "$untracked" | grep -v '^$') <(printf '%s\n' "$allowed_sorted"))"
unexpected="$(printf '%s\n%s\n' "$tracked_changed" "$unexpected_untracked" | grep -v '^$' | sort -u)"
scope_red=0
if [ -n "$unexpected" ] || [ -n "$missing" ]; then
    scope_red=1
fi
# shellcheck disable=SC2086
status_line "scope $( [ "$scope_red" -eq 0 ] && echo GREEN || echo RED ) base=$BASE_COMMIT tracked_changed=[$(echo $tracked_changed)] unexpected_untracked=[$(echo $unexpected_untracked)] missing=[$(echo $missing)] log=$SCOPE_LOG"

CONSUMERS=""
if [ -n "$unexpected" ]; then
    while IFS= read -r p; do
        [ -z "$p" ] && continue
        c="$(consumers_for "$p")"
        status_line "scope RED path=$p requires_full_suites=[$c]"
        CONSUMERS="$CONSUMERS $c"
    done <<< "$unexpected"
fi
# Unique consumer executables, minus the phase's own (its per-push lane below is already its full per-push suite).
# shellcheck disable=SC2086
CONSUMERS="$(printf '%s\n' $CONSUMERS | grep -v '^$' | grep -vx "$EXE" | sort -u | tr '\n' ' ')"
CONSUMERS="${CONSUMERS% }"
consumer_build_red=0
if [ -n "$CONSUMERS" ]; then
    CBUILD_LOG="$LOGDIR/build-consumers.log"
    b0="$(date +%s)"
    # shellcheck disable=SC2086
    "$CMAKE" --build "$BUILD_DIR" --config Release --target $CONSUMERS > "$CBUILD_LOG" 2>&1
    cb_status=$?
    b1="$(date +%s)"
    cwarn="$(grep -ciE "warning C|warning:" "$CBUILD_LOG" || true)"
    status_line "build-consumers targets=[$CONSUMERS] exit=$cb_status wall=$((b1 - b0))s warnings=${cwarn:-0} log=$CBUILD_LOG"
    if [ "$cb_status" -ne 0 ] || [ "${cwarn:-0}" -ne 0 ]; then
        consumer_build_red=1
    fi
fi

# ---------------------------------------------------------------------------------------------------------------
# 3a. Per-push lane of the phase's executable.
# ---------------------------------------------------------------------------------------------------------------
run_perpush() {
    local s0 s1 rc
    s0="$(date +%s)"
    "$BIN/$EXE.exe" "$PERPUSH_FILTER" -D 15 > "$PERPUSH_LOG" 2>&1
    rc=$?
    s1="$(date +%s)"
    echo "exit: $rc wall: $((s1 - s0)) s" >> "$PERPUSH_LOG"
    echo "perpush:$EXE exit=$rc wall=$((s1 - s0))s log=$PERPUSH_LOG" >> "$STATUS"
    return "$rc"
}

# ---------------------------------------------------------------------------------------------------------------
# 3b. [long] lane of the phase's own TUs: one shard per TEST_CASE, list generated from the exe.
# ---------------------------------------------------------------------------------------------------------------
LONG_LIST="$LONGDIR/long-cases.txt"
LIST_RAW="$LONGDIR/list-raw.txt"
list_fail=0
if ! "$BIN/$EXE.exe" --list-tests "$LONG_FILTER" --verbosity quiet > "$LIST_RAW" 2>&1; then
    list_fail=1
    status_line "long-list exit=nonzero (see $LIST_RAW)"
fi
tr -d '\r' < "$LIST_RAW" | grep -v '^[[:space:]]*$' > "$LONG_LIST"
long_count="$(wc -l < "$LONG_LIST" | tr -d ' ')"
if [ "${long_count:-0}" -eq 0 ]; then
    # The phase has [long] cases; an empty list is a broken filter or build, never a green.
    list_fail=1
    status_line "long-list RED: no [bass-morph][long] case listed"
fi
# xargs -P min(shards, cores - 4).
LONG_JOBS=$(( CORES - 4 ))
[ "$LONG_JOBS" -lt 1 ] && LONG_JOBS=1
if [ "${long_count:-0}" -gt 0 ] && [ "$long_count" -lt "$LONG_JOBS" ]; then
    LONG_JOBS="$long_count"
fi
status_line "long-list cases=$long_count jobs=$LONG_JOBS list=$LONG_LIST"

run_long_shard() {
    # $1 = exact TEST_CASE name
    local name="$1"
    local safe spec log s0 s1 rc
    safe="$(printf '%s' "$name" | tr -c 'A-Za-z0-9_.-' '_' | cut -c1-120)"
    log="$LONGDIR/${safe}.log"
    # Catch2 test-spec escaping: backslash, comma and brackets are special; '*' would be a wildcard.
    spec="$(printf '%s' "$name" | sed -e 's/\\/\\\\/g' -e 's/,/\\,/g' -e 's/\[/\\[/g' -e 's/\]/\\]/g' -e 's/\*/\\*/g')"
    s0="$(date +%s)"
    "$BIN/$EXE.exe" "$spec" -d yes > "$log" 2>&1
    rc=$?
    s1="$(date +%s)"
    if grep -qi "no test cases matched" "$log"; then
        rc=99
    fi
    echo "exit: $rc wall: $((s1 - s0)) s" >> "$log"
    echo "long:$name exit=$rc wall=$((s1 - s0))s log=$log" >> "$STATUS"
    return 0
}
export -f run_long_shard
export BIN EXE LONGDIR STATUS

# ---------------------------------------------------------------------------------------------------------------
# 3c. Consumer full per-push suites (scope RED only; empty with the expected diff).
# ---------------------------------------------------------------------------------------------------------------
run_consumer() {
    local exe="$1" log s0 s1 rc
    log="$LOGDIR/consumer-$exe.log"
    s0="$(date +%s)"
    if [ ! -f "$BIN/$exe.exe" ]; then
        echo "missing $BIN/$exe.exe" > "$log"
        rc=98
    else
        "$BIN/$exe.exe" "$PERPUSH_FILTER" > "$log" 2>&1
        rc=$?
    fi
    s1="$(date +%s)"
    echo "exit: $rc wall: $((s1 - s0)) s" >> "$log"
    echo "consumer:$exe exit=$rc wall=$((s1 - s0))s log=$log" >> "$STATUS"
}

lane_start="$(date +%s)"
run_perpush &
perpush_pid=$!

(
    l0="$(date +%s)"
    if [ "${long_count:-0}" -gt 0 ]; then
        tr '\n' '\0' < "$LONG_LIST" | xargs -0 -n 1 -P "$LONG_JOBS" bash -c 'run_long_shard "$1"' _
    fi
    l1="$(date +%s)"
    echo "long-lane shards=$long_count wall=$((l1 - l0))s" >> "$STATUS"
) &
long_pid=$!

consumer_pids=""
consumer_count=0
for c in $CONSUMERS; do
    run_consumer "$c" &
    consumer_pids="$consumer_pids $!"
    consumer_count=$((consumer_count + 1))
done

perpush_red=0
wait "$perpush_pid" || perpush_red=1
wait "$long_pid"
for p in $consumer_pids; do
    wait "$p"
done
lane_end="$(date +%s)"
status_line "lanes wall=$((lane_end - lane_start))s"

long_red="$(grep -E '^long:' "$STATUS" | grep -cv ' exit=0 ' || true)"
long_done="$(grep -cE '^long:' "$STATUS" || true)"
if [ "${long_done:-0}" -ne "${long_count:-0}" ]; then
    long_red=$(( ${long_red:-0} + 1 ))
    status_line "long-lane RED: $long_done of $long_count shards reported"
fi
[ "$list_fail" -ne 0 ] && long_red=$(( ${long_red:-0} + 1 ))

consumer_red="$(grep -E '^consumer:' "$STATUS" | grep -cv ' exit=0 ' || true)"
consumer_red=$(( ${consumer_red:-0} + consumer_build_red ))

# ---------------------------------------------------------------------------------------------------------------
# 4. Readings for the user (recorded, not gated here; the lane verdicts above are the gate).
#    SC-004: "SC004 family,pair,note,ramp_ms,g_sw,ratio_L,ratio_R,clicks_L,clicks_R" lines (bass_morph_click_test.cpp
#            bmcRecord); the worst max(ratio_L, ratio_R) per family.
#    SC-008: the tab-separated per-p table after "SC-008 showcase trajectory <mode> <note> ..." (bass_morph_trajectory_
#            test.cpp; columns p D_cx D_nl D_st D_br D_t L_K E_sub E_sub_out dyn_gain F_lock L_m floor ...).
#            (c) margin = L_K(p) - (min(L_K(0), L_K(1)) - 1.5 dB)  (kBmtDipDb = 1.5);
#            (d) margin = E_sub(p) - floor(p). Minimum per shard; >= 0 is inside the bar.
#    SC-017: "SC017 WORST <fs> <dBFS> dBFS (bar ...)" lines (bass_morph_aliasing_test.cpp).
#    Untagged slow cases: -D 15 prints every per-push case's duration ("<s> s: <name>"); those over 15 s are listed.
# ---------------------------------------------------------------------------------------------------------------
{
    echo "=== summary: per-shard verdict and wall clock, longest first (for the next run's sharding)"
    grep -E '^long:' "$STATUS" | sed -E 's/^long:(.+) exit=([^ ]+) wall=([0-9]+)s log=.*$/\3 s \1 exit=\2/' | sort -rn
    echo "=== summary: per-push cases over 15 s (re-tag candidates, T015 rule)"
    if [ -f "$PERPUSH_LOG" ]; then
        tr -d '\r' < "$PERPUSH_LOG" \
            | awk '/^[0-9]+(\.[0-9]+)? s: / { if ($1 + 0 > 15.0) print }' \
            | grep . || echo "(none)"
    fi
    echo "=== summary: SC-004 worst ratio per family (recorded)"
    sc004="$(cat "$LONGDIR"/*.log 2>/dev/null | tr -d '\r' | grep -E '^SC004 ' || true)"
    if [ -n "$sc004" ]; then
        printf '%s\n' "$sc004" | sed 's/^SC004 //' | awk -F, '
            { r = ($6 + 0 > $7 + 0) ? $6 + 0 : $7 + 0
              if (!($1 in worst) || r > worst[$1]) { worst[$1] = r; cell[$1] = $2 " " $3 " ramp " $4 " ms" }
              n[$1]++ }
            END { for (f in worst) printf "SC004 WORST %s ratio=%.6g cells=%d at %s\n", f, worst[f], n[f], cell[f] }' \
            | sort
    else
        echo "(no SC004 line found in the shard logs)"
    fi
    echo "=== summary: SC-008 (c) / (d) minimum margins per shard (recorded; dB, >= 0 is inside the bar)"
    sc008_found=0
    for f in "$LONGDIR"/*.log; do
        [ -f "$f" ] || continue
        tr -d '\r' < "$f" | grep -q '^SC-008 showcase trajectory ' || continue
        sc008_found=1
        tr -d '\r' < "$f" | awk -v shard="$(basename "$f" .log)" '
            function emit(   lkMin, i, mc, md, pc, pd) {
                if (n == 0) return
                lkMin = (lk[1] < lk[n]) ? lk[1] : lk[n]
                mc = 1e30; md = 1e30
                for (i = 1; i <= n; i++) {
                    if (lk[i] - (lkMin - 1.5) < mc) { mc = lk[i] - (lkMin - 1.5); pc = p[i] }
                    if (es[i] - fl[i] < md) { md = es[i] - fl[i]; pd = p[i] }
                }
                printf "SC008 %s | %s | (c) min margin %.4g dB at p %s | (d) min margin %.4g dB at p %s\n", shard, title, mc, pc, md, pd
                n = 0
            }
            /^SC-008 showcase trajectory / {
                if (inTable) emit()
                inTable = 1; hdr = 0; n = 0; title = $0; sub(/^SC-008 showcase trajectory /, "", title); next }
            inTable && /^p\t/ { hdr = 1; next }
            inTable && hdr && /^[-0-9.eE+]+\t/ {
                split($0, a, "\t"); n++; p[n] = a[1]; lk[n] = a[7] + 0; es[n] = a[8] + 0; fl[n] = a[13] + 0; next }
            inTable && hdr { inTable = 0; emit() }
            END { if (inTable) emit() }'
    done
    [ "$sc008_found" -eq 0 ] && echo "(no SC-008 showcase table found in the shard logs)"
    echo "=== summary: SC-017 worst dBFS per fs (recorded)"
    sc017="$(cat "$LONGDIR"/*.log 2>/dev/null | tr -d '\r' | grep -E '^SC017 WORST ' | sort || true)"
    if [ -n "$sc017" ]; then
        printf '%s\n' "$sc017"
    else
        echo "(no SC017 WORST line found in the shard logs)"
    fi
    if [ -n "$CONSUMERS" ]; then
        echo "=== summary: consumer full suites (scope RED)"
        grep -E '^consumer:|^build-consumers' "$STATUS"
    fi
} >> "$STATUS"

# ---------------------------------------------------------------------------------------------------------------
# Verdict.
# ---------------------------------------------------------------------------------------------------------------
suite_end="$(date +%s)"
overall=0
[ "${warnings:-0}" -ne 0 ] && overall=1
[ "$perpush_red" -ne 0 ] && overall=1
[ "${long_red:-0}" -ne 0 ] && overall=1
[ "$scope_red" -ne 0 ] && overall=1
[ "${consumer_red:-0}" -ne 0 ] && overall=1
echo "--- perpush-$EXE tail" >> "$STATUS"
tail -n 3 "$PERPUSH_LOG" | tr -d '\r' >> "$STATUS"
status_line "DONE $(now) $( [ "$overall" -eq 0 ] && echo GREEN || echo RED ) warnings=${warnings:-0} scope_red=$scope_red perpush_red=$perpush_red long_red=${long_red:-0}/$long_count consumer_red=${consumer_red:-0}/$consumer_count total_wall=$((suite_end - suite_start))s"
tail -n 50 "$STATUS"
exit "$overall"
