#!/usr/bin/env node
// =============================================================================
// extract-phase1-ref.js - Profundum Phase 2 (specs/profundum-phase2-edge-fold)
// T004 / SC-004(a): pinned Phase 1 reference generator.
//
// Reads the Phase 1 ProfundumCore header at commit 47e43918 via `git show` and
// writes dsp/tests/unit/systems/profundum_phase1_core_ref.h with exactly:
//   - a 4-line GENERATED comment prepended before the original line 1;
//   - `namespace Krate::DSP {`          -> `namespace Krate::DSP::ProfundumTest::Phase1Ref {`
//   - `}  // namespace Krate::DSP`      -> `}  // namespace Krate::DSP::ProfundumTest::Phase1Ref`
// Fails (exit 1) unless each anchor line occurs exactly once. Then prints a
// unified diff (computed in-script) of the base file against the output.
//
// Usage: node specs/profundum-phase2-edge-fold/extract-phase1-ref.js
// =============================================================================
'use strict';

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const kCommit = '47e43918';
const kBasePath = 'dsp/include/krate/dsp/systems/profundum_core.h';
const kOutPath = 'dsp/tests/unit/systems/profundum_phase1_core_ref.h';
const kRefNs = 'Krate::DSP::ProfundumTest::Phase1Ref';

const repoRoot = path.resolve(__dirname, '..', '..');

function fail(msg) {
  process.stderr.write(`extract-phase1-ref: ERROR: ${msg}\n`);
  process.exit(1);
}

let base;
try {
  base = execFileSync('git', ['show', `${kCommit}:${kBasePath}`], {
    cwd: repoRoot,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
} catch (e) {
  fail(`git show ${kCommit}:${kBasePath} failed: ${e.message}`);
}

// Preserve the base file's line ending style.
const eol = base.includes('\r\n') ? '\r\n' : '\n';
const baseLines = base.split(/\r?\n/);
// A trailing newline yields a final empty element; keep it so the join restores it.

function replaceAnchor(lines, from, to) {
  const hits = [];
  lines.forEach((l, i) => { if (l === from) hits.push(i); });
  if (hits.length !== 1) {
    fail(`anchor line ${JSON.stringify(from)} found ${hits.length} times (expected exactly 1)`);
  }
  lines[hits[0]] = to;
}

const outLines = baseLines.slice();
replaceAnchor(outLines, 'namespace Krate::DSP {', `namespace ${kRefNs} {`);
replaceAnchor(outLines, '}  // namespace Krate::DSP', `}  // namespace ${kRefNs}`);

const header = [
  '// GENERATED by specs/profundum-phase2-edge-fold/extract-phase1-ref.js',
  `// from ${kCommit}:${kBasePath} - DO NOT EDIT.`,
  '// SC-004(a) pinned Phase 1 reference;',
  `// only the enclosing namespace differs (${kRefNs}).`,
];
const finalLines = header.concat(outLines);
const outText = finalLines.join(eol);

const outAbs = path.join(repoRoot, kOutPath);
fs.writeFileSync(outAbs, outText, 'utf8');
process.stdout.write(`wrote ${kOutPath} (${Buffer.byteLength(outText, 'utf8')} bytes)\n\n`);

// ---------------------------------------------------------------------------
// Unified diff (LCS-based, 3 lines of context), computed in-script.
// ---------------------------------------------------------------------------
function unifiedDiff(a, b, nameA, nameB, context) {
  const n = a.length;
  const m = b.length;
  // lcs[i][j] = LCS length of a[i..] and b[j..]
  const lcs = Array.from({ length: n + 1 }, () => new Int32Array(m + 1));
  for (let i = n - 1; i >= 0; --i) {
    for (let j = m - 1; j >= 0; --j) {
      lcs[i][j] = a[i] === b[j] ? lcs[i + 1][j + 1] + 1
                                : Math.max(lcs[i + 1][j], lcs[i][j + 1]);
    }
  }
  // Edit script: entries {op: ' '|'-'|'+', text, ai, bi}
  const ops = [];
  let i = 0;
  let j = 0;
  while (i < n || j < m) {
    if (i < n && j < m && a[i] === b[j]) {
      ops.push({ op: ' ', text: a[i], ai: i, bi: j }); ++i; ++j;
    } else if (i < n && (j >= m || lcs[i + 1][j] >= lcs[i][j + 1])) {
      ops.push({ op: '-', text: a[i], ai: i, bi: j }); ++i;
    } else {
      ops.push({ op: '+', text: b[j], ai: i, bi: j }); ++j;
    }
  }
  const out = [`--- ${nameA}`, `+++ ${nameB}`];
  let k = 0;
  while (k < ops.length) {
    if (ops[k].op === ' ') { ++k; continue; }
    // Build a hunk around this change, merging changes within 2*context.
    let start = Math.max(0, k - context);
    let end = k;
    for (;;) {
      while (end < ops.length && ops[end].op !== ' ') ++end;
      let next = end;
      while (next < ops.length && ops[next].op === ' ') ++next;
      if (next < ops.length && next - end <= 2 * context) { end = next; continue; }
      end = Math.min(ops.length, end + context);
      break;
    }
    const hunk = ops.slice(start, end);
    const aStart = hunk[0].ai;
    const bStart = hunk[0].bi;
    const aCount = hunk.filter((o) => o.op !== '+').length;
    const bCount = hunk.filter((o) => o.op !== '-').length;
    out.push(`@@ -${aCount ? aStart + 1 : aStart},${aCount} +${bCount ? bStart + 1 : bStart},${bCount} @@`);
    for (const o of hunk) out.push(o.op + o.text);
    k = end;
  }
  return out.join('\n') + '\n';
}

process.stdout.write(unifiedDiff(baseLines, finalLines,
  `a/${kBasePath} (${kCommit})`, `b/${kOutPath}`, 3));
