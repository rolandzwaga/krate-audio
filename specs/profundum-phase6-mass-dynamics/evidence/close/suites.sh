#!/usr/bin/env bash
# Profundum Phase 6, task T022 close lane: full suites + [long] lane (SC-020; plan S14.2).
#
# Run from the main loop AFTER T019 (harvest.sh) and T020, DETACHED, so it survives the 2 h background-task
# ceiling (Git Bash, from the Bash tool):
#   nohup bash specs/profundum-phase6-mass-dynamics/evidence/close/suites.sh \
#       > specs/profundum-phase6-mass-dynamics/evidence/run-log/close/suites.out 2>&1 & disown
# and run tidy.sh concurrently. Watch evidence/run-log/close/status.txt; its last line is "DONE ...".
#
# Steps:
#   1. One rebuild of dsp_processors_tests dsp_systems_tests (wall clock recorded; the count of
#      "warning C|warning:" lines in the build log must be 0).
#   2. Concurrently:
#      (a) the two per-push lanes, filter "~[long]~[performance]~[perf]~[benchmark]~[!benchmark]",
#          each to evidence/run-log/close/perpush-<exe>.log (with -D 15: every case over 15 s is printed, so an
#          untagged case that should be [long] shows up in the log);
#      (b) the [long] lane: one shard per [long] TEST_CASE of the two exes, the list generated by
#          <exe> --list-tests "[long]~[performance]~[perf]~[benchmark]~[!benchmark]" --verbosity quiet
#          (never hand-kept; about 45 shards: SC-001(b) 12, SC-001(c) 12, SC-003 12, SC-005 9, SC-010 3),
#          run through xargs -P 24, each shard to evidence/run-log/close/long/<exe>__<case>.log.
#   3. git diff --stat 02fecee1 -- dsp/include (+ untracked files under dsp/include) must name only the four new
#      Phase 6 headers (SC-020, FR-044).
#   4. Summary block (FR-048 readings for the user): the SC-003 E0 / E1 K-weighted spans (plan S1 C-1) and the
#      SC-010 vacuous-cell list (plan S1 C-3), extracted from the shard logs.
# Status file evidence/run-log/close/status.txt: one line per lane / shard: name, exit code, wall clock (s).
# Exit code: 0 only if every lane is green.
set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"
cd "$REPO" || exit 2

SPEC="specs/profundum-phase6-mass-dynamics"
CMAKE="/c/Program Files/CMake/bin/cmake.exe"
BUILD_DIR="build/windows-x64-release"
BIN="$BUILD_DIR/bin/Release"
EXES="dsp_processors_tests dsp_systems_tests"
PERPUSH_FILTER="~[long]~[performance]~[perf]~[benchmark]~[!benchmark]"
LONG_FILTER="[long]~[performance]~[perf]~[benchmark]~[!benchmark]"
LONG_JOBS=24
BASE_COMMIT="02fecee1"
LOGDIR="$SPEC/evidence/run-log/close"
LONGDIR="$LOGDIR/long"
STATUS="$LOGDIR/status.txt"

# The four new Phase 6 headers (tasks.md "File map") plus the one ratified modification (G7-1 clamp in true_peak_limiter.h,
# user ruling 2026-10-18 G9-3, spec FR-044); nothing else under dsp/include may differ from 02fecee1.
ALLOWED_HEADERS="dsp/include/krate/dsp/processors/period_peak_detector.h
dsp/include/krate/dsp/processors/transient_shaper.h
dsp/include/krate/dsp/processors/true_peak_limiter.h
dsp/include/krate/dsp/systems/mass_dynamics.h
dsp/include/krate/dsp/systems/mass_law.h"

mkdir -p "$LOGDIR" "$LONGDIR"
rm -f "$LONGDIR"/*.log "$LONGDIR"/*.status

now() { date -u +%Y-%m-%dT%H:%M:%SZ; }
status_line() { echo "$*" >> "$STATUS"; }

suite_start="$(date +%s)"
echo "START $(now) commit $(git rev-parse --short HEAD 2>/dev/null || echo unknown)" > "$STATUS"

# ---------------------------------------------------------------------------------------------------------------
# 1. One rebuild of the two exes.
# ---------------------------------------------------------------------------------------------------------------
BUILD_LOG="$LOGDIR/build.log"
t0="$(date +%s)"
# shellcheck disable=SC2086
"$CMAKE" --build "$BUILD_DIR" --config Release --target $EXES > "$BUILD_LOG" 2>&1
build_status=$?
t1="$(date +%s)"
warnings="$(grep -ciE "warning C|warning:" "$BUILD_LOG" || true)"
status_line "build exit=$build_status wall=$((t1 - t0))s warnings=${warnings:-0} log=$BUILD_LOG"
if [ "$build_status" -ne 0 ]; then
    status_line "DONE $(now) RED: build failed; no test lane ran (see $BUILD_LOG)"
    tail -n 30 "$BUILD_LOG"
    exit 1
fi
for exe in $EXES; do
    if [ ! -f "$BIN/$exe.exe" ]; then
        status_line "DONE $(now) RED: $BIN/$exe.exe missing after the build"
        exit 1
    fi
done

# ---------------------------------------------------------------------------------------------------------------
# 2a. Per-push lanes (two exes, concurrently).
# ---------------------------------------------------------------------------------------------------------------
run_perpush() {
    local exe="$1"
    local log="$LOGDIR/perpush-$exe.log"
    local s0 s1 rc
    s0="$(date +%s)"
    "$BIN/$exe.exe" "$PERPUSH_FILTER" -D 15 > "$log" 2>&1
    rc=$?
    s1="$(date +%s)"
    echo "exit: $rc wall: $((s1 - s0)) s" >> "$log"
    echo "perpush:$exe exit=$rc wall=$((s1 - s0))s log=$log" >> "$STATUS"
    return "$rc"
}

# ---------------------------------------------------------------------------------------------------------------
# 2b. [long] lane: one shard per TEST_CASE, list generated from the exes.
# ---------------------------------------------------------------------------------------------------------------
LONG_LIST="$LONGDIR/long-cases.tsv"
: > "$LONG_LIST"
list_fail=0
for exe in $EXES; do
    if ! "$BIN/$exe.exe" --list-tests "$LONG_FILTER" --verbosity quiet > "$LONGDIR/list-$exe.txt" 2>&1; then
        # Catch2 returns non-zero when the filter matches nothing; an empty list is not an error.
        if [ -s "$LONGDIR/list-$exe.txt" ] && ! grep -qi "no test cases matched" "$LONGDIR/list-$exe.txt"; then
            list_fail=1
            status_line "long-list:$exe exit=nonzero (see $LONGDIR/list-$exe.txt)"
            continue
        fi
        : > "$LONGDIR/list-$exe.txt"
    fi
    tr -d '\r' < "$LONGDIR/list-$exe.txt" | grep -v '^[[:space:]]*$' | while IFS= read -r name; do
        printf '%s\t%s\n' "$exe" "$name" >> "$LONG_LIST"
    done
done
long_count="$(wc -l < "$LONG_LIST" | tr -d ' ')"
status_line "long-list cases=$long_count jobs=$LONG_JOBS list=$LONG_LIST"

run_long_shard() {
    # $1 = exe, $2 = exact TEST_CASE name
    local exe="$1" name="$2"
    local safe spec log s0 s1 rc
    safe="$(printf '%s' "$name" | tr -c 'A-Za-z0-9_.-' '_' | cut -c1-120)"
    log="$LONGDIR/${exe}__${safe}.log"
    # Catch2 test-spec escaping: backslash, comma and brackets are special; '*' would be a wildcard.
    spec="$(printf '%s' "$name" | sed -e 's/\\/\\\\/g' -e 's/,/\\,/g' -e 's/\[/\\[/g' -e 's/\]/\\]/g' -e 's/\*/\\*/g')"
    s0="$(date +%s)"
    "$BIN/$exe.exe" "$spec" -d yes > "$log" 2>&1
    rc=$?
    s1="$(date +%s)"
    if grep -qi "no test cases matched" "$log"; then
        rc=99
    fi
    echo "exit: $rc wall: $((s1 - s0)) s" >> "$log"
    echo "long:$exe:$name exit=$rc wall=$((s1 - s0))s log=$log" >> "$STATUS"
    return 0
}
export -f run_long_shard
export BIN LONGDIR STATUS

lane_start="$(date +%s)"
pids=""
for exe in $EXES; do
    run_perpush "$exe" &
    pids="$pids $!"
done

(
    l0="$(date +%s)"
    if [ "$long_count" -gt 0 ]; then
        while IFS=$'\t' read -r e n; do printf '%s\0%s\0' "$e" "$n"; done < "$LONG_LIST" \
            | xargs -0 -n 2 -P "$LONG_JOBS" bash -c 'run_long_shard "$1" "$2"' _
    fi
    l1="$(date +%s)"
    echo "long-lane shards=$long_count wall=$((l1 - l0))s" >> "$STATUS"
) &
long_pid=$!

perpush_red=0
for p in $pids; do
    wait "$p" || perpush_red=1
done
wait "$long_pid"
lane_end="$(date +%s)"
status_line "lanes wall=$((lane_end - lane_start))s"

long_red="$(grep -E '^long:' "$STATUS" | grep -cv ' exit=0 ' || true)"
long_done="$(grep -cE '^long:' "$STATUS" || true)"
if [ "${long_done:-0}" -ne "${long_count:-0}" ]; then
    long_red=$(( ${long_red:-0} + 1 ))
    status_line "long-lane RED: $long_done of $long_count shards reported"
fi
[ "$list_fail" -ne 0 ] && long_red=$(( ${long_red:-0} + 1 ))

# ---------------------------------------------------------------------------------------------------------------
# 3. SC-020 / FR-044: only the four new headers differ under dsp/include.
# ---------------------------------------------------------------------------------------------------------------
SC020_LOG="$LOGDIR/sc020-diff.log"
{
    echo "=== git diff --stat $BASE_COMMIT -- dsp/include"
    git diff --stat "$BASE_COMMIT" -- dsp/include
    echo "=== untracked under dsp/include"
    git ls-files --others --exclude-standard -- dsp/include
} > "$SC020_LOG" 2>&1
changed="$( { git diff --name-only "$BASE_COMMIT" -- dsp/include; git ls-files --others --exclude-standard -- dsp/include; } \
    | tr -d '\r' | sort -u)"
unexpected="$(comm -23 <(printf '%s\n' "$changed" | grep -v '^$') <(printf '%s\n' "$ALLOWED_HEADERS" | sort -u))"
missing="$(comm -13 <(printf '%s\n' "$changed" | grep -v '^$') <(printf '%s\n' "$ALLOWED_HEADERS" | sort -u))"
sc020_red=0
if [ -n "$unexpected" ] || [ -n "$missing" ]; then
    sc020_red=1
fi
status_line "sc020 $( [ "$sc020_red" -eq 0 ] && echo GREEN || echo RED ) unexpected=[$(echo $unexpected)] missing=[$(echo $missing)] log=$SC020_LOG"
cat "$SC020_LOG" >> "$STATUS"

# ---------------------------------------------------------------------------------------------------------------
# 4. FR-048 readings for the user (recorded, not gated here; the shard verdicts above are the gate).
#    C-1: SC-003 E0 / E1 K-weighted spans, from the "SC-003 <fixture> <note>: span(P) ..." lines that
#         mass_law_spectral_test.cpp prints (mlsPrint, std::cout) in the MassLaw_LevelSlopeBounded_* shards.
#    C-3: SC-010 vacuous cells, from the "VACUOUS" spec-method lines that mass_dynamics_aliasing_test.cpp prints
#         (mdaPrintSpec), each prefixed with the "[T016 SC-010] fs ... <note>" header line it belongs to.
# ---------------------------------------------------------------------------------------------------------------
{
    echo "=== FR-048 summary: SC-003 E0 / E1 K-weighted spans (plan S1 C-1, recorded)"
    sc003_found=0
    for f in "$LONGDIR"/dsp_systems_tests__MassLaw_LevelSlopeBounded_*.log; do
        [ -f "$f" ] || continue
        if tr -d '\r' < "$f" | grep -E '^SC-003 [^ ]+ E[01]: span\(P\)'; then
            sc003_found=1
        fi
    done
    [ "$sc003_found" -eq 0 ] && echo "(no SC-003 E0 / E1 line found in the LevelSlopeBounded shard logs)"
    echo "=== FR-048 summary: SC-010 vacuous spec-method cells (plan S1 C-3, recorded; the residual method gates)"
    vac_found=0
    for f in "$LONGDIR"/dsp_systems_tests__MassDynamics_AliasingE0E2_*.log; do
        [ -f "$f" ] || continue
        vac="$(tr -d '\r' < "$f" | awk '/^\[T016 SC-010\] fs / { hdr = $0 } /VACUOUS/ { print hdr " |" $0 }')"
        if [ -n "$vac" ]; then
            printf '%s\n' "$vac"
            vac_found=1
        fi
    done
    [ "$vac_found" -eq 0 ] && echo "(no VACUOUS cell found in the AliasingE0E2 shard logs)"
} >> "$STATUS"

# ---------------------------------------------------------------------------------------------------------------
# Verdict.
# ---------------------------------------------------------------------------------------------------------------
suite_end="$(date +%s)"
overall=0
[ "${warnings:-0}" -ne 0 ] && overall=1
[ "$perpush_red" -ne 0 ] && overall=1
[ "${long_red:-0}" -ne 0 ] && overall=1
[ "$sc020_red" -ne 0 ] && overall=1
for exe in $EXES; do
    echo "--- perpush-$exe tail" >> "$STATUS"
    tail -n 3 "$LOGDIR/perpush-$exe.log" | tr -d '\r' >> "$STATUS"
done
status_line "DONE $(now) $( [ "$overall" -eq 0 ] && echo GREEN || echo RED ) warnings=${warnings:-0} perpush_red=$perpush_red long_red=${long_red:-0}/$long_count sc020_red=$sc020_red total_wall=$((suite_end - suite_start))s"
tail -n 40 "$STATUS"
exit "$overall"
