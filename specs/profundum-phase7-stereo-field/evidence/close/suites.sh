#!/usr/bin/env bash
# Profundum Phase 7, task T019 close lane: change-set scope check, per-push lane and the phase's own [long] lane
# (SC-015; plan S14.2). Structure copied from specs/profundum-phase6-mass-dynamics/evidence/close/suites.sh, with the
# scope rule of 2026-10-18 (Phase 6 ruling G9-4, root CLAUDE.md "Run only the tests the change set can reach").
#
# Run from the main loop AFTER T015 (harvest.sh) and T016, DETACHED, so it survives the 2 h background-task ceiling
# (Git Bash, from the Bash tool):
#   nohup bash specs/profundum-phase7-stereo-field/evidence/close/suites.sh \
#       > specs/profundum-phase7-stereo-field/evidence/run-log/close/suites.out 2>&1 & disown
# and run tidy.sh concurrently. Watch evidence/run-log/close/status.txt; its last line is "DONE ...".
#
# Steps:
#   1. One rebuild of dsp_systems_tests (wall clock recorded; the count of "warning C|warning:" lines in the build
#      log must be 0).
#   2. Change-set scope (BASE_COMMIT 4599d180): git diff --name-only over dsp/include dsp/src plugins/shared
#      tests/test_helpers, plus untracked files under dsp/include, must name ONLY
#      dsp/include/krate/dsp/systems/bass_stereo_field.h (FR-073, SC-015). Any other path is RED and is written to
#      the status file with the consumer executables it would pull in; the lanes below still run, and this script
#      never adds consumer suites itself (an unexpected modified shared header is a defect, not a lane). With the
#      expected diff no consumer suite (Ruinae, Seraphis, Vorago, Innexus, other dsp_*_tests) runs.
#   3. Concurrently:
#      (a) the per-push lane of the phase's executable:
#          dsp_systems_tests.exe "~[long]~[performance]~[perf]~[benchmark]~[!benchmark]" -D 15
#          to evidence/run-log/close/perpush-dsp_systems_tests.log (every case over 15 s printed, so an untagged slow
#          case shows up);
#      (b) the [long] lane of the PHASE'S OWN TUs ONLY: one shard per TEST_CASE in the list generated by
#          dsp_systems_tests.exe --list-tests "[stereo-field][long]~[performance]~[perf]~[benchmark]~[!benchmark]"
#          --verbosity quiet (never hand-kept; about 194 shards), run through xargs -P 28, each shard to
#          evidence/run-log/close/long/<case>.log. Never every [long] case of the executable.
#   4. Summary block: the C-1 / C-2 / C-17 readings (from the per-push log), the SC-006 validity table, the SC-001
#      worst cells per shard, and the wall clock per shard (for the next run's sharding).
# A timing-budget assertion of an untouched (non-Phase-7) case that fails under this concurrent lane is recorded as
# load, not re-run (root CLAUDE.md).
# Status file evidence/run-log/close/status.txt: one line per lane / shard: name, exit code, wall clock (s).
# Exit code: 0 only if every lane is green.
set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"
cd "$REPO" || exit 2

SPEC="specs/profundum-phase7-stereo-field"
CMAKE="/c/Program Files/CMake/bin/cmake.exe"
BUILD_DIR="build/windows-x64-release"
BIN="$BUILD_DIR/bin/Release"
EXE="dsp_systems_tests"
PERPUSH_FILTER="~[long]~[performance]~[perf]~[benchmark]~[!benchmark]"
LONG_FILTER="[stereo-field][long]~[performance]~[perf]~[benchmark]~[!benchmark]"
LONG_JOBS=28
BASE_COMMIT="4599d180"
SCOPE_PATHS="dsp/include dsp/src plugins/shared tests/test_helpers"
LOGDIR="$SPEC/evidence/run-log/close"
LONGDIR="$LOGDIR/long"
STATUS="$LOGDIR/status.txt"
PERPUSH_LOG="$LOGDIR/perpush-$EXE.log"

# The one new Phase 7 header (tasks.md "File map"); nothing else under the scope paths may differ from 4599d180.
ALLOWED="dsp/include/krate/dsp/systems/bass_stereo_field.h"

mkdir -p "$LOGDIR" "$LONGDIR"
rm -f "$LONGDIR"/*.log "$LONGDIR"/*.txt

now() { date -u +%Y-%m-%dT%H:%M:%SZ; }
status_line() { echo "$*" >> "$STATUS"; }

suite_start="$(date +%s)"
echo "START $(now) commit $(git rev-parse --short HEAD 2>/dev/null || echo unknown) base $BASE_COMMIT" > "$STATUS"

# ---------------------------------------------------------------------------------------------------------------
# 1. One rebuild of dsp_systems_tests.
# ---------------------------------------------------------------------------------------------------------------
BUILD_LOG="$LOGDIR/build.log"
t0="$(date +%s)"
"$CMAKE" --build "$BUILD_DIR" --config Release --target "$EXE" > "$BUILD_LOG" 2>&1
build_status=$?
t1="$(date +%s)"
warnings="$(grep -ciE "warning C|warning:" "$BUILD_LOG" || true)"
status_line "build exit=$build_status wall=$((t1 - t0))s warnings=${warnings:-0} log=$BUILD_LOG"
if [ "$build_status" -ne 0 ]; then
    status_line "DONE $(now) RED: build failed; no test lane ran (see $BUILD_LOG)"
    tail -n 30 "$BUILD_LOG"
    exit 1
fi
if [ ! -f "$BIN/$EXE.exe" ]; then
    status_line "DONE $(now) RED: $BIN/$EXE.exe missing after the build"
    exit 1
fi

# ---------------------------------------------------------------------------------------------------------------
# 2. Change-set scope (FR-073, SC-015). Recorded before the lanes so a RED is visible while they run.
# ---------------------------------------------------------------------------------------------------------------
# Consumer executables a changed path would pull in (reported only; never run from here).
consumers_for() {
    local p="$1" layers="" plugins="" inc out="" l pl
    case "$p" in
        dsp/include/krate/dsp/core/*)       layers="core primitives processors systems effects" ;;
        dsp/include/krate/dsp/primitives/*) layers="primitives processors systems effects" ;;
        dsp/include/krate/dsp/processors/*) layers="processors systems effects" ;;
        dsp/include/krate/dsp/systems/*)    layers="systems effects" ;;
        dsp/include/krate/dsp/effects/*)    layers="effects" ;;
        dsp/src/*|dsp/include/*|tests/test_helpers/*) layers="core primitives processors systems effects" ;;
    esac
    case "$p" in
        dsp/include/krate/dsp/*)
            inc="krate/dsp/${p#dsp/include/krate/dsp/}"
            # Direct includers only; a transitive consumer still needs a check by hand.
            plugins="$(grep -rlF "$inc" plugins 2>/dev/null | cut -d/ -f2 | sort -u | tr '\n' ' ')" ;;
        dsp/src/*|plugins/shared/*|tests/test_helpers/*)
            plugins="disrumpo gradus innexus iterum membrum ruinae seraphis shared vorago" ;;
    esac
    for l in $layers; do out="$out dsp_${l}_tests"; done
    for pl in $plugins; do
        case "$pl" in
            iterum) out="$out plugin_tests approval_tests" ;;
            *)      out="$out ${pl}_tests" ;;
        esac
    done
    echo "${out# }"
}

SCOPE_LOG="$LOGDIR/scope-diff.log"
# shellcheck disable=SC2086
{
    echo "=== git diff --name-only $BASE_COMMIT -- $SCOPE_PATHS"
    git diff --name-only "$BASE_COMMIT" -- $SCOPE_PATHS
    echo "=== untracked under dsp/include"
    git ls-files --others --exclude-standard -- dsp/include
} > "$SCOPE_LOG" 2>&1
# shellcheck disable=SC2086
changed="$( { git diff --name-only "$BASE_COMMIT" -- $SCOPE_PATHS; git ls-files --others --exclude-standard -- dsp/include; } \
    | tr -d '\r' | grep -v '^$' | sort -u)"
unexpected="$(comm -23 <(printf '%s\n' "$changed" | grep -v '^$') <(printf '%s\n' "$ALLOWED" | sort -u))"
missing="$(comm -13 <(printf '%s\n' "$changed" | grep -v '^$') <(printf '%s\n' "$ALLOWED" | sort -u))"
scope_red=0
if [ -n "$unexpected" ] || [ -n "$missing" ]; then
    scope_red=1
fi
status_line "scope $( [ "$scope_red" -eq 0 ] && echo GREEN || echo RED ) base=$BASE_COMMIT unexpected=[$(echo $unexpected)] missing=[$(echo $missing)] log=$SCOPE_LOG"
if [ -n "$unexpected" ]; then
    while IFS= read -r p; do
        [ -z "$p" ] && continue
        status_line "scope RED path=$p would_pull_in=[$(consumers_for "$p")] (not run here: a defect, not a lane)"
    done <<< "$unexpected"
fi

# ---------------------------------------------------------------------------------------------------------------
# 3a. Per-push lane of the phase's executable.
# ---------------------------------------------------------------------------------------------------------------
run_perpush() {
    local s0 s1 rc
    s0="$(date +%s)"
    "$BIN/$EXE.exe" "$PERPUSH_FILTER" -D 15 > "$PERPUSH_LOG" 2>&1
    rc=$?
    s1="$(date +%s)"
    echo "exit: $rc wall: $((s1 - s0)) s" >> "$PERPUSH_LOG"
    echo "perpush:$EXE exit=$rc wall=$((s1 - s0))s log=$PERPUSH_LOG" >> "$STATUS"
    return "$rc"
}

# ---------------------------------------------------------------------------------------------------------------
# 3b. [long] lane of the phase's own TUs: one shard per TEST_CASE, list generated from the exe.
# ---------------------------------------------------------------------------------------------------------------
LONG_LIST="$LONGDIR/long-cases.txt"
LIST_RAW="$LONGDIR/list-raw.txt"
list_fail=0
if ! "$BIN/$EXE.exe" --list-tests "$LONG_FILTER" --verbosity quiet > "$LIST_RAW" 2>&1; then
    list_fail=1
    status_line "long-list exit=nonzero (see $LIST_RAW)"
fi
tr -d '\r' < "$LIST_RAW" | grep -v '^[[:space:]]*$' > "$LONG_LIST"
long_count="$(wc -l < "$LONG_LIST" | tr -d ' ')"
if [ "${long_count:-0}" -eq 0 ]; then
    # The phase has [long] cases; an empty list is a broken filter or build, never a green.
    list_fail=1
    status_line "long-list RED: no [stereo-field][long] case listed"
fi
status_line "long-list cases=$long_count jobs=$LONG_JOBS list=$LONG_LIST"

run_long_shard() {
    # $1 = exact TEST_CASE name
    local name="$1"
    local safe spec log s0 s1 rc
    safe="$(printf '%s' "$name" | tr -c 'A-Za-z0-9_.-' '_' | cut -c1-120)"
    log="$LONGDIR/${safe}.log"
    # Catch2 test-spec escaping: backslash, comma and brackets are special; '*' would be a wildcard.
    spec="$(printf '%s' "$name" | sed -e 's/\\/\\\\/g' -e 's/,/\\,/g' -e 's/\[/\\[/g' -e 's/\]/\\]/g' -e 's/\*/\\*/g')"
    s0="$(date +%s)"
    "$BIN/$EXE.exe" "$spec" -d yes > "$log" 2>&1
    rc=$?
    s1="$(date +%s)"
    if grep -qi "no test cases matched" "$log"; then
        rc=99
    fi
    echo "exit: $rc wall: $((s1 - s0)) s" >> "$log"
    echo "long:$name exit=$rc wall=$((s1 - s0))s log=$log" >> "$STATUS"
    return 0
}
export -f run_long_shard
export BIN EXE LONGDIR STATUS

lane_start="$(date +%s)"
run_perpush &
perpush_pid=$!

(
    l0="$(date +%s)"
    if [ "${long_count:-0}" -gt 0 ]; then
        tr '\n' '\0' < "$LONG_LIST" | xargs -0 -n 1 -P "$LONG_JOBS" bash -c 'run_long_shard "$1"' _
    fi
    l1="$(date +%s)"
    echo "long-lane shards=$long_count wall=$((l1 - l0))s" >> "$STATUS"
) &
long_pid=$!

perpush_red=0
wait "$perpush_pid" || perpush_red=1
wait "$long_pid"
lane_end="$(date +%s)"
status_line "lanes wall=$((lane_end - lane_start))s"

long_red="$(grep -E '^long:' "$STATUS" | grep -cv ' exit=0 ' || true)"
long_done="$(grep -cE '^long:' "$STATUS" || true)"
if [ "${long_done:-0}" -ne "${long_count:-0}" ]; then
    long_red=$(( ${long_red:-0} + 1 ))
    status_line "long-lane RED: $long_done of $long_count shards reported"
fi
[ "$list_fail" -ne 0 ] && long_red=$(( ${long_red:-0} + 1 ))

# ---------------------------------------------------------------------------------------------------------------
# 4. Readings for the user (recorded, not gated here; the lane verdicts above are the gate).
#    C-1:  "[T006 SC-005 C-1" lines (bass_stereo_field_test.cpp, SafetyStageGates / SafetyStageMidBitExact): the
#          mid-mismatch count and the largest ratio to C-1's bound.
#    C-2:  "C-2 record]" lines (StageLrInLrOutDirtyState, AnchorBitIdenticalDirtyState): the side-decay lengths.
#    C-17: "[T004 C-17]" lines (CurveInterpolationMixedPairs): the mixed-pair excursions beyond the endpoints.
#    SC-006: "BSF_SC006," lines (spectral test, SafetyStageAttenuation [long] shard): the validity table.
#    SC-001: "BSF_SC001_WORST," lines (monosum test), per shard.
#    Untagged slow cases: -D 15 prints every per-push case's duration ("<s> s: <name>"); those over 15 s are listed.
# ---------------------------------------------------------------------------------------------------------------
{
    echo "=== summary: C-1 / C-2 / C-17 readings (per-push log, recorded)"
    if [ -f "$PERPUSH_LOG" ]; then
        tr -d '\r' < "$PERPUSH_LOG" | grep -E '^\[T006 SC-005 C-1|C-2 record\]|^\[T004 C-17\]' \
            || echo "(no C-1 / C-2 / C-17 line found in $PERPUSH_LOG)"
    fi
    echo "=== summary: per-push cases over 15 s (re-tag candidates, T016 bullet 2 rule)"
    if [ -f "$PERPUSH_LOG" ]; then
        tr -d '\r' < "$PERPUSH_LOG" \
            | awk '/^[0-9]+(\.[0-9]+)? s: / { if ($1 + 0 > 15.0) print }' \
            | grep . || echo "(none)"
    fi
    echo "=== summary: SC-006 validity table (recorded)"
    sc006_found=0
    for f in "$LONGDIR"/*.log "$PERPUSH_LOG"; do
        [ -f "$f" ] || continue
        if tr -d '\r' < "$f" | grep -E '^BSF_SC006,'; then
            sc006_found=1
        fi
    done
    [ "$sc006_found" -eq 0 ] && echo "(no BSF_SC006 line found)"
    echo "=== summary: SC-001 worst cells per shard (recorded)"
    sc001_found=0
    for f in "$LONGDIR"/*.log; do
        [ -f "$f" ] || continue
        lines="$(tr -d '\r' < "$f" | grep -E '^BSF_SC001_WORST,' || true)"
        if [ -n "$lines" ]; then
            printf '%s\n' "$lines" | sed "s|^|$(basename "$f" .log) \| |"
            sc001_found=1
        fi
    done
    [ "$sc001_found" -eq 0 ] && echo "(no BSF_SC001_WORST line found in the shard logs)"
    echo "=== summary: wall clock per shard, longest first (for the next run's sharding)"
    grep -E '^long:' "$STATUS" | sed -E 's/^long:([^ ]+) exit=([^ ]+) wall=([0-9]+)s.*$/\3 s \1 exit=\2/' | sort -rn
} >> "$STATUS"

# ---------------------------------------------------------------------------------------------------------------
# Verdict.
# ---------------------------------------------------------------------------------------------------------------
suite_end="$(date +%s)"
overall=0
[ "${warnings:-0}" -ne 0 ] && overall=1
[ "$perpush_red" -ne 0 ] && overall=1
[ "${long_red:-0}" -ne 0 ] && overall=1
[ "$scope_red" -ne 0 ] && overall=1
echo "--- perpush-$EXE tail" >> "$STATUS"
tail -n 3 "$PERPUSH_LOG" | tr -d '\r' >> "$STATUS"
status_line "DONE $(now) $( [ "$overall" -eq 0 ] && echo GREEN || echo RED ) warnings=${warnings:-0} scope_red=$scope_red perpush_red=$perpush_red long_red=${long_red:-0}/$long_count total_wall=$((suite_end - suite_start))s"
tail -n 40 "$STATUS"
exit "$overall"
